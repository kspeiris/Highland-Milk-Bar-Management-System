using System.Globalization;
using System.Text;

namespace HighlandMilkBar.Infrastructure.Services.Reports;

/// <summary>
/// Minimal dependency-free PDF writer for tabular reports. Produces a valid PDF 1.4 file with
/// Helvetica text, pagination and repeated table headers. ASCII only (non-ASCII is replaced).
/// </summary>
internal sealed class SimplePdf
{
    private const float PageWidth = 595f;
    private const float PageHeight = 842f;
    private const float Margin = 40f;
    private const float Top = 800f;
    private const float Bottom = 50f;
    private const float RowHeight = 16f;

    private readonly List<string> _pages = new();
    private StringBuilder _content = new();
    private float _y = Top;

    public void Begin()
    {
        _pages.Clear();
        _content = new StringBuilder();
        _y = Top;
    }

    public void End()
    {
        _pages.Add(_content.ToString());

        // Footnote + page numbers (total known now).
        for (var i = 0; i < _pages.Count; i++)
        {
            var footer = new StringBuilder(_pages[i]);
            footer.Append("q 0.6 w ")
                  .Append(F(Margin)).Append(' ').Append(F(38f)).Append(" m ")
                  .Append(F(PageWidth - Margin)).Append(' ').Append(F(38f)).Append(" l S Q\r\n");
            footer.Append("BT /F1 8 Tf 1 0 0 1 ").Append(F(Margin)).Append(' ').Append(F(28f))
                  .Append(" Tm (Generated by Highland Milk Bar Management System) Tj ET\r\n");
            footer.Append("BT /F1 8 Tf 1 0 0 1 ").Append(F(PageWidth - Margin - 70f)).Append(' ').Append(F(28f))
                  .Append(" Tm (Page ").Append(i + 1).Append(" of ").Append(_pages.Count).Append(") Tj ET\r\n");
            _pages[i] = footer.ToString();
        }
    }

    public void Title(string text) => Draw(Margin, ref _y, text, 18f, bold: true, gapAfter: 8f);
    public void Subtitle(string text) => Draw(Margin, ref _y, text, 13f, bold: true, gapAfter: 6f);
    public void Line(string text) => Draw(Margin, ref _y, text, 10f, bold: false, gapAfter: 4f);
    public void Gap(float height) => _y -= height;

    public void Table(IReadOnlyList<string> headers, IReadOnlyList<IReadOnlyList<string>> rows)
    {
        var count = headers.Count;
        if (count == 0) return;

        var usable = PageWidth - 2 * Margin;
        var colWidth = usable / count;

        EnsureSpaceForRow();
        DrawRow(headers, colWidth, 9.5f, bold: true);
        Underline(usable);

        foreach (var row in rows)
        {
            if (_y - RowHeight < Bottom)
            {
                NewPage();
                DrawRow(headers, colWidth, 9.5f, bold: true);
                Underline(usable);
            }
            DrawRow(row, colWidth, 9f, bold: false);
        }
    }

    private void DrawRow(IReadOnlyList<string> cells, float colWidth, float size, bool bold)
    {
        for (var i = 0; i < cells.Count; i++)
        {
            var x = Margin + i * colWidth + 3f;
            var text = Truncate(cells[i] ?? string.Empty, colWidth - 6f, size);
            Text(x, _y, text, size, bold);
        }
        _y -= RowHeight;
    }

    private void EnsureSpaceForRow()
    {
        if (_y - RowHeight < Bottom) NewPage();
    }

    private void Underline(float usable)
    {
        Line(Margin, _y + RowHeight - 4f, Margin + usable, _y + RowHeight - 4f);
    }

    private void NewPage()
    {
        _pages.Add(_content.ToString());
        _content = new StringBuilder();
        _y = Top;
    }

    private void Draw(float x, ref float y, string text, float size, bool bold, float gapAfter)
    {
        Text(x, y, text, size, bold);
        y -= size + gapAfter;
    }

    private void Text(float x, float y, string text, float size, bool bold)
    {
        _content.Append("BT /").Append(bold ? "F2" : "F1").Append(' ')
                .Append(size.ToString("0.##", CultureInfo.InvariantCulture)).Append(" Tf 1 0 0 1 ")
                .Append(F(x)).Append(' ').Append(F(y)).Append(" Tm (")
                .Append(Escape(text)).Append(") Tj ET\r\n");
    }

    private void Line(float x1, float y1, float x2, float y2)
    {
        _content.Append("q 0.6 w ").Append(F(x1)).Append(' ').Append(F(y1)).Append(" m ")
                .Append(F(x2)).Append(' ').Append(F(y2)).Append(" l S Q\r\n");
    }

    private static string Truncate(string text, float width, float size)
    {
        var maxChars = Math.Max(1, (int)(width / (size * 0.52f)));
        if (text.Length <= maxChars) return text;
        return maxChars <= 1 ? "." : text[..(maxChars - 1)] + ".";
    }

    private static string Escape(string text)
    {
        var sb = new StringBuilder(text.Length + 8);
        foreach (var ch in text)
        {
            if (ch is >= ' ' and <= '~')
            {
                switch (ch)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '(': sb.Append("\\("); break;
                    case ')': sb.Append("\\)"); break;
                    default: sb.Append(ch); break;
                }
            }
            else sb.Append('?');
        }
        return sb.ToString();
    }

    private static string F(float value) => value.ToString("0.##", CultureInfo.InvariantCulture);

    public byte[] ToBytes()
    {
        var objects = new List<string>();
        var pageCount = _pages.Count;

        // 1 catalog, 2 pages, 3 font F1, 4 font F2, then per page: page, content
        objects.Add("<< /Type /Catalog /Pages 2 0 R >>"); // 1
        var kids = string.Join(' ', Enumerable.Range(0, pageCount).Select(i => $"{5 + i * 2} 0 R"));
        objects.Add($"<< /Type /Pages /Kids [{kids}] /Count {pageCount} >>"); // 2
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"); // 3
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"); // 4

        for (var i = 0; i < pageCount; i++)
        {
            var contentId = 6 + i * 2;
            objects.Add($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {F(PageWidth)} {F(PageHeight)}] " +
                        "/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> " +
                        $"/Contents {contentId} 0 R >>");
            var stream = _pages[i];
            objects.Add($"<< /Length {Encoding.ASCII.GetByteCount(stream)} >>\r\nstream\r\n{stream}endstream");
        }

        var pdf = new StringBuilder();
        pdf.Append("%PDF-1.4\r\n");
        var offsets = new List<int>();
        for (var i = 0; i < objects.Count; i++)
        {
            offsets.Add(Encoding.ASCII.GetByteCount(pdf.ToString()));
            pdf.Append(i + 1).Append(" 0 obj\r\n").Append(objects[i]).Append("\r\nendobj\r\n");
        }

        var xrefStart = Encoding.ASCII.GetByteCount(pdf.ToString());
        pdf.Append("xref\r\n0 ").Append(objects.Count + 1).Append('\r');
        pdf.Append("0000000000 65535 f\r");
        foreach (var off in offsets)
            pdf.Append(off.ToString("D10", CultureInfo.InvariantCulture)).Append(" 00000 n\r");
        pdf.Append("trailer\r\n<< /Size ").Append(objects.Count + 1).Append(" /Root 1 0 R >>\r\n");
        pdf.Append("startxref\r\n").Append(xrefStart).Append("\r\n%%EOF");

        return Encoding.ASCII.GetBytes(pdf.ToString());
    }
}